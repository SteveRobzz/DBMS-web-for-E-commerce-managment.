-- 1. Users of the application (both admins and customers) ------------
CREATE TABLE APP_USERS (
    USER_ID        NUMBER,
    USERNAME       VARCHAR2(30)  NOT NULL,
    PASSWORD_HASH  VARCHAR2(64)  NOT NULL,          -- SHA-256 hex of password
    FULL_NAME      VARCHAR2(80)  NOT NULL,
    EMAIL          VARCHAR2(100),
    PHONE          VARCHAR2(15),
    CITY           VARCHAR2(50),
    USER_ROLE      VARCHAR2(10)  DEFAULT 'CUSTOMER' NOT NULL,
    CREATED_AT     DATE          DEFAULT SYSDATE,
    CONSTRAINT PK_APP_USERS      PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USERS_EMAIL    UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_ROLE     CHECK (USER_ROLE IN ('ADMIN', 'CUSTOMER'))
);

-- 2. Product categories, each with its own GST rate ------------------
CREATE TABLE CATEGORIES (
    CATEGORY_ID    NUMBER,
    CATEGORY_NAME  VARCHAR2(50)  NOT NULL,
    GST_RATE       NUMBER(5,2)   DEFAULT 18 NOT NULL,  -- percentage
    CONSTRAINT PK_CATEGORIES   PRIMARY KEY (CATEGORY_ID),
    CONSTRAINT UQ_CATEGORY_NAME UNIQUE (CATEGORY_NAME),
    CONSTRAINT CK_GST_RATE     CHECK (GST_RATE BETWEEN 0 AND 28)
);

-- 3. Products / inventory --------------------------------------------
CREATE TABLE PRODUCTS (
    PRODUCT_ID     NUMBER,
    PRODUCT_NAME   VARCHAR2(100) NOT NULL,
    CATEGORY_ID    NUMBER        NOT NULL,
    PRICE          NUMBER(10,2)  NOT NULL,             -- price before GST
    STOCK          NUMBER(6)     DEFAULT 0 NOT NULL,
    DESCRIPTION    VARCHAR2(300),
    IS_ACTIVE      CHAR(1)       DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_PRODUCTS        PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT FK_PRODUCTS_CAT    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID),
    CONSTRAINT CK_PRODUCTS_PRICE  CHECK (PRICE > 0),
    CONSTRAINT CK_PRODUCTS_STOCK  CHECK (STOCK >= 0),
    CONSTRAINT CK_PRODUCTS_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

-- 4. Discount coupons ------------------------------------------------
CREATE TABLE COUPONS (
    COUPON_CODE     VARCHAR2(20)  NOT NULL,
    DISCOUNT_PCT    NUMBER(5,2)   NOT NULL,
    MIN_ORDER_VALUE NUMBER(10,2)  DEFAULT 0 NOT NULL,
    MAX_DISCOUNT    NUMBER(10,2)  NOT NULL,
    VALID_TILL      DATE          NOT NULL,
    IS_ACTIVE       CHAR(1)       DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_COUPONS        PRIMARY KEY (COUPON_CODE),
    CONSTRAINT CK_COUPON_PCT     CHECK (DISCOUNT_PCT > 0 AND DISCOUNT_PCT <= 90),
    CONSTRAINT CK_COUPON_ACTIVE  CHECK (IS_ACTIVE IN ('Y', 'N'))
);

-- 5. Orders (one row per checkout) -----------------------------------
CREATE TABLE ORDERS (
    ORDER_ID       NUMBER,
    USER_ID        NUMBER        NOT NULL,
    ORDER_DATE     DATE          DEFAULT SYSDATE NOT NULL,
    SUBTOTAL       NUMBER(12,2)  NOT NULL,
    DISCOUNT       NUMBER(12,2)  DEFAULT 0 NOT NULL,
    GST_AMOUNT     NUMBER(12,2)  DEFAULT 0 NOT NULL,
    SHIPPING       NUMBER(8,2)   DEFAULT 0 NOT NULL,
    COD_CHARGE     NUMBER(8,2)   DEFAULT 0 NOT NULL,
    GRAND_TOTAL    NUMBER(12,2)  NOT NULL,
    COUPON_CODE    VARCHAR2(20),
    PAYMENT_MODE   VARCHAR2(12)  NOT NULL,
    SHIP_CITY      VARCHAR2(50)  NOT NULL,
    ORDER_STATUS   VARCHAR2(12)  DEFAULT 'PLACED' NOT NULL,
    CONSTRAINT PK_ORDERS          PRIMARY KEY (ORDER_ID),
    CONSTRAINT FK_ORDERS_USER     FOREIGN KEY (USER_ID) REFERENCES APP_USERS(USER_ID),
    CONSTRAINT CK_ORDERS_PAYMENT  CHECK (PAYMENT_MODE IN ('UPI', 'CARD', 'NETBANKING', 'COD')),
    CONSTRAINT CK_ORDERS_STATUS   CHECK (ORDER_STATUS IN ('PLACED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT CK_ORDERS_TOTAL    CHECK (GRAND_TOTAL >= 0)
);

-- 6. Line items of every order ---------------------------------------
CREATE TABLE ORDER_ITEMS (
    ITEM_ID        NUMBER,
    ORDER_ID       NUMBER        NOT NULL,
    PRODUCT_ID     NUMBER        NOT NULL,
    QUANTITY       NUMBER(4)     NOT NULL,
    UNIT_PRICE     NUMBER(10,2)  NOT NULL,     -- price at the time of order
    GST_RATE       NUMBER(5,2)   NOT NULL,
    LINE_TOTAL     NUMBER(12,2)  NOT NULL,     -- QUANTITY * UNIT_PRICE
    CONSTRAINT PK_ORDER_ITEMS     PRIMARY KEY (ITEM_ID),
    CONSTRAINT FK_ITEMS_ORDER     FOREIGN KEY (ORDER_ID)   REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITEMS_PRODUCT   FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT CK_ITEMS_QTY       CHECK (QUANTITY > 0)
);


-- Sequences + triggers to auto-generate primary keys (Oracle 11g) -----
CREATE SEQUENCE SEQ_USERS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE OR REPLACE TRIGGER TRG_APP_USERS_PK
BEFORE INSERT ON APP_USERS
FOR EACH ROW
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        SELECT SEQ_USERS.NEXTVAL INTO :NEW.USER_ID FROM DUAL;
    END IF;
END;
/

